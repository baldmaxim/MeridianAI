# -*- coding: utf-8 -*-
"""Переформулировка реплики в язык договора — перед поиском по документам встречи.

Поиск по словам не понимает смысла: на «срок сдачи сдвигаем на месяц, цена прежняя» он не
находит п. 5.1 «компенсация затрат при увеличении срока производства работ» — общих слов нет.
Короткий вызов модели называет, как эта тема и наши встречные права записаны в договоре;
поиск идёт и по реплике, и по этим формулировкам (см. get_relevant_chunks_for_meeting).
"""

import re

EXPANSION_PROMPT = """Задача для поиска по тексту договора генподряда (текст договора есть у поисковой системы, не у тебя).
По последней реплике переговоров выпиши 8–14 поисковых формулировок в языке договора подряда:
- чем регулируется то, о чём говорит собеседник;
- наши встречные права по этой теме: компенсация затрат, продление сроков, индексация цены,
  приостановление работ, дополнительное соглашение, основания освобождения от ответственности.
Формат ответа — ТОЛЬКО формулировки в одну строку через точку с запятой. Без вступления,
без пояснений, без нумерации и без номеров пунктов.

Реплики:
{dialog}"""

DIALOG_TAIL_CHARS = 1200
MAX_TERMS_CHARS = 600

_LIST_MARK = re.compile(r"^\s*(?:[-*•]|\d+[.)])\s*", re.MULTILINE)


def build_expansion_prompt(dialog: str) -> str:
    """Последние реплики: тема подсказки — это последняя реплика, а не начало встречи."""
    return EXPANSION_PROMPT.format(dialog=(dialog or "")[-DIALOG_TAIL_CHARS:])


def parse_expansion(raw: str | None) -> str:
    """Формулировки одной строкой. Разметку, нумерацию и переносы модели убираем."""
    text = _LIST_MARK.sub("", (raw or "").replace("*", ""))
    text = re.sub(r"\s*\n\s*", "; ", text).strip(" ;")
    return text[:MAX_TERMS_CHARS]
